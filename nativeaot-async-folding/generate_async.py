#!/usr/bin/env python3
"""Generates N trivial `async Task<int>` methods.

Built with optimizations, every async method gets its own struct state machine, so Native AOT
compiles a separate copy of AsyncStateMachineBox<int, TSM>.MoveNext, AsyncMethodBuilderCore.Start<TSM>
and friends for each of them. The copies are byte-identical apart from relocations, which is what
method body folding (on by default for Release in .NET 10) has to deduplicate.
"""
import argparse
import os

parser = argparse.ArgumentParser()
parser.add_argument("-n", "--count", type=int, default=4000, help="number of async methods")
parser.add_argument("-c", "--chunk", type=int, default=200, help="methods per generated class")
parser.add_argument("-o", "--output", default=os.path.join(os.path.dirname(__file__), "AsyncFolding", "Generated.cs"))
args = parser.parse_args()

lines = ["// <auto-generated/> by generate_async.py", "using System;", "using System.Collections.Generic;",
         "using System.Threading.Tasks;", "", "namespace AsyncFolding", "{"]
classes = (args.count + args.chunk - 1) // args.chunk
for c in range(classes):
    lines.append(f"    internal static class Async{c}")
    lines.append("    {")
    first, last = c * args.chunk, min((c + 1) * args.chunk, args.count)
    for i in range(first, last):
        lines.append(f"        private static async Task<int> M{i}(int x) {{ await Task.Yield(); return x + {i}; }}")
    lines.append("")
    lines.append("        public static void Register(List<Func<int, Task<int>>> methods)")
    lines.append("        {")
    for i in range(first, last):
        lines.append(f"            methods.Add(M{i});")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
lines.append("    internal static class Generated")
lines.append("    {")
lines.append(f"        public const int Count = {args.count};")
lines.append("")
lines.append("        public static List<Func<int, Task<int>>> All()")
lines.append("        {")
lines.append(f"            var methods = new List<Func<int, Task<int>>>({args.count});")
for c in range(classes):
    lines.append(f"            Async{c}.Register(methods);")
lines.append("            return methods;")
lines.append("        }")
lines.append("    }")
lines.append("}")

with open(args.output, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {args.count} async methods in {classes} classes to {args.output}")
